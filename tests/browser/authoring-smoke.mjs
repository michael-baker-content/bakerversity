import assert from 'node:assert/strict'
export async function authoringSmoke(page,origin,fixtureOrigin) {
 page.on('dialog',dialog=>dialog.accept())
 const request=async(path,body)=>{const response=await fetch(fixtureOrigin+path,body?{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}:undefined);assert.ok(response.ok,await response.text().catch(()=>''));}
 const mode=async value=>request('/api/fixture/mode',{mode:value})
 await page.goto(origin+'/admin/courses/smoke')
 await page.getByRole('link',{name:'New lesson',exact:true}).click()
 await page.locator('input[type=text]').first().fill('Smoke lesson')
 await page.getByRole('button',{name:'Save lesson',exact:true}).click()
 await page.getByRole('link',{name:'Smoke lesson',exact:true}).click()
 const title=page.locator('input[type=text]').first()
 await title.fill('Saved lesson draft')
 await page.getByRole('button',{name:'Save draft',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Changes saved.'}).waitFor()
 await page.getByLabel('When saving').selectOption('publish')
 await page.getByRole('button',{name:'Publish changes',exact:true}).click()
 await page.getByRole('button',{name:'Back to course overview',exact:true}).click()
 await page.getByRole('link',{name:'Saved lesson draft',exact:true}).waitFor()
 await page.getByRole('link',{name:'New assessment',exact:true}).click()
 await page.locator('input[type=text]').first().fill('Smoke quiz')
 await page.getByRole('button',{name:/Create/}).click()
 await page.getByRole('button',{name:'+ Add question',exact:true}).click()
 await page.locator('.tiptap').first().fill('Choose the correct answer')
 await page.getByPlaceholder('Option A',{exact:true}).fill('Wrong')
 await page.getByPlaceholder('Option C',{exact:true}).fill('Right')
 await page.getByRole('radio',{name:'Mark option C as correct'}).check()
 await page.getByRole('button',{name:'Save question',exact:true}).click()
 await page.getByText('✓ Right',{exact:true}).waitFor()
 // Reopening and saving preserves the compacted correct answer.
 await page.getByRole('button',{name:'Edit',exact:true}).click()
 await page.getByRole('button',{name:'Save question',exact:true}).waitFor()
 await page.getByRole('button',{name:'Save question',exact:true}).click()
 await page.getByRole('button',{name:'+ Add question',exact:true}).click()
 await page.getByRole('button',{name:'True / false',exact:true}).click()
 await page.locator('.tiptap').first().fill('This is true')
 await page.getByRole('button',{name:'Save question',exact:true}).click()
 await page.getByText('2 questions',{exact:false}).first().waitFor()
 const assessmentId=new URL(page.url()).pathname.split('/').pop()
 await page.getByLabel('When saving').selectOption('publish')
 await page.getByRole('button',{name:'Save',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Changes saved.'}).waitFor()
 assert.ok(await page.getByRole('button',{name:'+ Add question',exact:true}).isDisabled())
 const student=await page.context().newPage();await student.goto(origin+'/student/'+assessmentId)
 await student.getByRole('radio',{name:'B. Right',exact:true}).check()
 await student.getByRole('radio',{name:'True',exact:true}).check()
 await student.getByRole('button',{name:/Submit/}).click()
 await student.locator('#assessment-results').waitFor()
 const attempts=await(await fetch(fixtureOrigin+'/api/fixture/attempts')).json();assert.equal(attempts.length,1);assert.equal(attempts[0].score,100)
 await student.close()
 await page.locator('form input[type=text]').first().fill('Unsaved settings')
 await mode('validation');await page.getByRole('button',{name:'Save',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'Simulated validation failure'}).waitFor()
 assert.equal(await page.locator('form input[type=text]').first().inputValue(),'Unsaved settings')
 await mode('conflict');await page.getByRole('button',{name:'Save',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'another session'}).waitFor()
 assert.ok(await page.getByRole('button',{name:'Save',exact:true}).isDisabled())
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download recovery copy',exact:true}).click();await download
 await mode('normal');await page.reload()
 await page.locator('form input[type=text]').first().fill('Ambiguous settings')
 await mode('commit-lost');await page.getByRole('button',{name:'Save',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'Simulated lost response'}).waitFor()
 assert.ok(await page.getByRole('button',{name:'Save',exact:true}).isDisabled())
 await mode('normal')
 await page.goto(origin+'/admin/courses/smoke')
 await page.getByRole('link',{name:'New page',exact:true}).click()
 await page.locator('input[type=text]').first().fill('Smoke course page')
 await page.getByRole('button',{name:'Save page',exact:true}).click()
 await page.getByRole('link',{name:'Smoke course page',exact:true}).click()
 await page.locator('input[type=text]').first().fill('Published course page')
 await page.getByLabel('When saving').selectOption('publish')
 await page.getByRole('button',{name:'Save page',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Changes saved.'}).waitFor()
 await page.getByRole('button',{name:'Revision history',exact:true}).click()
 await page.getByRole('button',{name:'Load into editor',exact:true}).first().click()
 await page.getByRole('button',{name:'Save page',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Changes saved.'}).waitFor()
 await page.getByRole('link',{name:'Back to course overview',exact:true}).click()
 await page.getByRole('link',{name:'Published course page',exact:true}).waitFor()
 console.log('Verified create/save/publish/overview, answer mapping, published locks, student grading, validation/conflict/uncertain-save recovery')
}
