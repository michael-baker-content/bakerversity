// Run with Playwright CLI against a fresh isolated authoring-harness lesson.
async page => {
 const check=(v,m)=>{if(!v)throw Error(m)}
 check(new URL(page.url()).origin==='http://localhost:3101','Isolated harness only')
 const status=text=>page.getByRole('status').filter({hasText:text})
 const btn=name=>page.getByRole('button',{name,exact:true})
 await btn('Show invisible characters').click()
 await status('No unsaved changes.').waitFor()
 await btn('Find and replace').click()
 await page.getByRole('textbox',{name:'Find text',exact:true}).fill('Local')
 await status('1 of 1 matches').waitFor()
 await status('No unsaved changes.').waitFor()
 await btn('Close search').click()
 await btn('Show invisible characters').click()
 const editor=page.getByRole('textbox').filter({hasText:'Local test content'})
 await editor.click()
 await page.keyboard.press('Control+End')
 await page.keyboard.insertText('żółć żółć żółci ŻÓŁĆ\u00a0English')
 await page.keyboard.press('Home')
 await page.keyboard.press('Control+Shift+ArrowRight')
 await page.getByRole('combobox',{name:'Text language',exact:true}).selectOption('pl')
 await btn('Highlight').click()
 await btn('Save draft').click()
 await status('Changes saved.').waitFor()
 let fixture=await (await page.request.get('http://localhost:3101/api/harness')).json()
 let content=JSON.stringify(fixture.lesson.content)
 check(content.includes('textLanguage')&&content.includes('"language":"pl"')&&content.includes('highlight'),'Marks not saved')
 await page.reload()
 await page.getByText('żółć',{exact:true}).first().waitFor()
 await btn('Find and replace').click()
 await page.getByRole('textbox',{name:'Find text',exact:true}).fill('żółć')
 await page.getByRole('checkbox',{name:'Whole words',exact:true}).check()
 await status('of 3 matches').waitFor()
 await page.getByRole('checkbox',{name:'Match case',exact:true}).check()
 await status('of 2 matches').waitFor()
 await page.getByRole('textbox',{name:'Replace with',exact:true}).fill('cel')
 await btn('Replace all (2)').click()
 await status('No matches').waitFor()
 await status('You have unsaved changes.').waitFor()
 await btn('Close search').click()
 await page.getByRole('textbox').filter({hasText:'Local test content'}).click()
 await page.keyboard.press('Control+z')
 await page.getByText('żółć',{exact:true}).first().waitFor()
 await btn('Save draft').click()
 await status('Changes saved.').waitFor()
 fixture=await (await page.request.get('http://localhost:3101/api/harness')).json()
 content=JSON.stringify(fixture.lesson.content)
 check(content.includes('żółć')&&!content.includes('"text":"cel'),'Undo failed')
 check(content.includes('highlight')&&content.includes('textLanguage'),'Replacement undo lost formatting')
 return 'PASS: inspection/search do not dirty content; language and highlight persist; Polish whole-word/case search, replace all and undo'
}
