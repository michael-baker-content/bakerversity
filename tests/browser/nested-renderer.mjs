import assert from 'node:assert/strict'
export async function nestedRendererSmoke(page,origin){
 const errors=[];const onError=error=>errors.push(error.message);page.on('pageerror',onError)
 try {
  await page.goto(origin+'/renderer-check')
  const first=page.locator('[data-lesson-island="0"]')
  const second=page.locator('[data-lesson-island="1"]')
  await first.getByRole('radio').first().check()
  await second.getByRole('radio').first().check()
  await page.getByRole('button',{name:'Refresh presentation 0',exact:true}).click()
  await page.getByRole('button',{name:'Refresh presentation 1',exact:true}).waitFor()
  assert.equal(await first.getByRole('radio').first().isChecked(),true)
  assert.equal(await second.getByRole('radio').first().isChecked(),true)
  await first.getByRole('button',{name:'Check answers',exact:true}).click()
  await first.getByText('✓ Correct',{exact:true}).waitFor()
  await second.getByRole('button',{name:'Check answers',exact:true}).click()
  await second.getByText('✓ Correct',{exact:true}).waitFor()
  await page.locator('td [data-lesson-island="2"] svg').first().waitFor()
  assert.equal(await page.locator('[data-callout] li [data-lesson-island="1"]').count(),1)
  const slideshow=page.getByRole('region',{name:'Slideshow fixture',exact:true})
  await slideshow.getByText('Slide description 1',{exact:true}).waitFor()
  assert.equal(await slideshow.getByText('Slide description 2',{exact:true}).isVisible(),false)
  await slideshow.getByRole('button',{name:'Next',exact:true}).click()
  await slideshow.getByText('Slide description 2',{exact:true}).waitFor()
  await slideshow.locator('[data-active="true"] .katex').waitFor()
  await slideshow.focus();await page.keyboard.press('ArrowLeft')
  await slideshow.getByText('Slide description 1',{exact:true}).waitFor()
  await page.emulateMedia({media:'print'})
  assert.equal(await slideshow.getByText('Slide description 2',{exact:true}).isVisible(),true)
  await page.emulateMedia({media:'screen'})
  const references=page.locator('.footnote-reference a')
  assert.equal(await references.count(),2)
  await references.first().click()
  const noteTarget=await references.first().getAttribute('href')
  assert.equal(new URL(page.url()).hash,noteTarget)
  const returns=page.locator('.footnotes .footnote-returns a')
  assert.equal(await returns.count(),2)
  const returnTarget=await returns.last().getAttribute('href')
  await returns.last().click()
  assert.equal(new URL(page.url()).hash,returnTarget)
  await page.getByRole('button',{name:'Replace fixture',exact:true}).click()
  await page.getByText('Replacement content',{exact:true}).waitFor()
  assert.equal(await page.locator('[data-lesson-island]').count(),0)
  assert.deepEqual(errors,[])
 }catch(error){
  console.error('Nested renderer diagnostics:',JSON.stringify({errors,islands:await page.locator('[data-lesson-island]').evaluateAll(elements=>elements.map(element=>({index:element.getAttribute('data-lesson-island'),connected:element.isConnected,children:element.childElementCount,text:element.textContent?.slice(0,200)}))).catch(()=>[])}))
  throw error
 }finally{page.off('pageerror',onError)}
}
